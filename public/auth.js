(() => {
  let pending;

  async function readStatus() {
    const response = await fetch('/api/auth/status', { cache: 'no-store' });
    if (!response.ok) throw new Error(`Authentication check failed (${response.status}).`);
    return response.json();
  }

  function buildDialog() {
    const dialog = document.createElement('dialog');
    dialog.id = 'auth-dialog';
    dialog.className = 'operation-dialog auth-dialog';
    const form = document.createElement('form');
    form.method = 'dialog';
    const kicker = document.createElement('span'); kicker.className = 'dialog-kicker'; kicker.textContent = 'PRIVATE PI CONSOLE';
    const title = document.createElement('h2'); title.textContent = 'Unlock JARVIS';
    const copy = document.createElement('p'); copy.textContent = 'Enter the private dashboard PIN generated by install-pi.sh. Camera, microphone, Google status, Docker data, and controls stay locked until authentication succeeds.';
    const label = document.createElement('label'); label.textContent = 'DASHBOARD PIN';
    const input = document.createElement('input'); input.type = 'password'; input.inputMode = 'numeric'; input.autocomplete = 'current-password'; input.required = true; input.maxLength = 64;
    const error = document.createElement('p'); error.className = 'dialog-error';
    const button = document.createElement('button'); button.className = 'confirm-operation'; button.type = 'submit'; button.textContent = 'UNLOCK PRIVATE CONSOLE';
    label.append(input); form.append(kicker, title, copy, label, error, button); dialog.append(form); document.body.append(dialog);
    return { dialog, form, input, error, button };
  }

  window.ensureDashboardAuthentication = () => {
    if (pending) return pending;
    pending = (async () => {
      const status = await readStatus();
      if (!status.required || status.authenticated) return true;
      const ui = buildDialog();
      ui.dialog.addEventListener('cancel', (event) => event.preventDefault());
      ui.dialog.showModal(); ui.input.focus();
      await new Promise((resolve) => {
        ui.form.addEventListener('submit', async (event) => {
          event.preventDefault(); ui.error.textContent = ''; ui.button.disabled = true; ui.button.textContent = 'VERIFYING';
          try {
            const response = await fetch('/api/auth/login', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ pin: ui.input.value }) });
            const payload = await response.json().catch(() => ({}));
            if (!response.ok) throw new Error(payload.error || `Login failed (${response.status}).`);
            ui.dialog.close(); ui.dialog.remove(); resolve(true);
          } catch (error) {
            ui.error.textContent = error.message; ui.input.select();
          } finally { ui.button.disabled = false; ui.button.textContent = 'UNLOCK PRIVATE CONSOLE'; }
        });
      });
      return true;
    })();
    return pending;
  };
})();
